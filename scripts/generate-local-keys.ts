import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Wallet } from "ethers";

const envPath = resolve(process.cwd(), ".env");
const existing = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
const values = new Map<string, string>();
for (const line of existing.split(/\r?\n/)) {
  const i = line.indexOf("=");
  if (i > 0) values.set(line.slice(0, i).trim(), line.slice(i + 1).trim());
}

const force = process.argv.includes("--force");
if (values.get("DEPLOYER_PRIVATE_KEY") && !force) {
  console.error(".env already contains local test accounts. Re-run with --force only if you intend to replace them.");
  process.exit(1);
}

const roles = ["DEPLOYER", "BUYER", "ATTESTOR", "RESOLVER"] as const;
const generated = roles.map((role) => ({ role, wallet: Wallet.createRandom() }));

for (const { role, wallet } of generated) {
  values.set(`${role}_PRIVATE_KEY`, wallet.privateKey);
  values.set(`${role}_ADDRESS`, wallet.address);
}
values.set("BOHR_RPC_URL", values.get("BOHR_RPC_URL") || "https://rpc.bohr.life");
values.set("BOHR_CHAIN_ID", "968");
values.set("BOHR_EXPLORER_URL", "https://scan.bohr.life");
values.set("GRACE_PERIOD_SECONDS", values.get("GRACE_PERIOD_SECONDS") || "300");

const header = [
  "# Local-only BOT Chain Bohr testnet burner accounts.",
  "# Generated by scripts/generate-local-keys.ts. Never commit this file.",
  "# Attestor and resolver must remain distinct. Fund these from the faucet/test BOT.",
  "",
];
const lines = [...values.entries()].map(([key, value]) => `${key}=${value}`);
writeFileSync(envPath, `${header.join("\n")}\n${lines.join("\n")}\n`, { mode: 0o600 });

console.log("Generated local test accounts in .env (ignored by git).");
for (const { role, wallet } of generated) console.log(`${role.padEnd(8)} ${wallet.address}`);
console.log("\nFaucet: https://faucet.botchain.ai/basic (claim 10 test BOT to DEPLOYER_ADDRESS).");
