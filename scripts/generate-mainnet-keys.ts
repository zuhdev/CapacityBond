import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Wallet } from "ethers";

/**
 * Generates FRESH mainnet deployment keys (owner/deployer, buyer, attestor,
 * resolver) and writes them into .env, backing up any existing environment file
 * first. This must never overwrite a file that already holds funded or
 * production-custody keys. Testnet burner keys live in .env.bohr after the
 * backup and are never to be reused on mainnet.
 */

const envPath = resolve(process.cwd(), ".env");
const backupPath = resolve(process.cwd(), ".env.bohr");

const existing = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
if (existing.includes("DEPLOYER_PRIVATE_KEY=") || existing.includes("DEPLOYER_PRIVATE_KEY =")) {
  console.error(
    ".env already contains a DEPLOYER_PRIVATE_KEY. Refusing to overwrite.\n" +
      "If you really intend to replace it (e.g. new emergency burner), move the current\n" +
      "file aside first, e.g. copy it to .env.bohr.",
  );
  process.exit(1);
}

if (existsSync(backupPath)) {
  console.error(`.env.bohr already exists. Refusing to overwrite it.`);
  process.exit(1);
}

const backup = existing ? `${existing}\n` : "# Backup of the previous environment file.\n# No DEPLOYER_PRIVATE_KEY or funded keys live here.\n";
writeFileSync(backupPath, backup, { mode: 0o600 });

const roles = ["DEPLOYER", "BUYER", "ATTESTOR", "RESOLVER"] as const;
const generated = roles.map((role) => ({ role, wallet: Wallet.createRandom() }));

const lines: string[] = [];
lines.push("# Mainnet deployment keys. Generated by scripts/generate-mainnet-keys.ts.");
lines.push("# BACKUP OF TESTNET ROLES: .env.bohr");
lines.push("# WARNING: emergency burner keys for mainnet. Prefer hardware wallets in production.");
lines.push(`BOT_MAINNET_RPC_URL=https://rpc.botchain.ai`);
lines.push(`GRACE_PERIOD_SECONDS=300`);
lines.push("");
for (const { role, wallet } of generated) {
  lines.push(`${role}_PRIVATE_KEY=${wallet.privateKey}`);
  lines.push(`${role}_ADDRESS=${wallet.address}`);
  lines.push("");
}
lines.push("# Seed / acceptance runners only. Local burner accounts funded by the deployer.");
lines.push(`BUYER_PRIVATE_KEY=${generated[1].wallet.privateKey}`);
lines.push(`ATTESTOR_PRIVATE_KEY=${generated[2].wallet.privateKey}`);
lines.push(`RESOLVER_PRIVATE_KEY=${generated[3].wallet.privateKey}`);

writeFileSync(envPath, `${lines.join("\n")}\n`, { mode: 0o600 });

console.log("Generated fresh mainnet deployment keys in .env (ignored by git).");
for (const { role, wallet } of generated) {
  console.log(`${role.padEnd(8)} ${wallet.address}`);
}
console.log("\nTestnet burner keys moved to: .env.bohr (do not reuse on mainnet).");
console.log("\nFunding: fund the DEPLOYER with at least 0.05 BOT for deployment.");
console.log("Minimum required by the deploy script: 0.05 BOT.");
console.log("Recommended: fund ~0.2 BOT for deploy, sanity, verification, and monitoring gas.");
